#!/usr/bin/env bash
# Regenerates the dependency section of LICENSES.md. Run before each push and before submission.
set -euo pipefail
cd "$(dirname "$0")/.."
out=$(mktemp)
{
  echo "<!-- generated by scripts/license-audit.sh on $(date -u +%Y-%m-%d) -->"
  echo "### Backend (Python, via pip-licenses)"
  echo
  (cd backend && uv run -q pip-licenses --from=mixed --format=markdown --with-urls)
  if [[ -f frontend/package.json ]]; then
    echo
    echo "### Frontend (npm, via license-checker)"
    echo
    echo "Production dependencies only (what ships in the built app), one row per package:"
    echo
    echo "| Package | License | Repository |"
    echo "|---|---|---|"
    (cd frontend && npx --yes license-checker --production --csv) | tail -n +2 \
      | python3 -c 'import csv,sys; [print(f"| {r[0]} | {r[1]} | {r[2]} |") for r in csv.reader(sys.stdin)]'
  fi
  echo
  echo "Locked but not installed on Linux, so not listed above: colorama (BSD-3-Clause), win32-setctime (MIT) and"
  echo "tzdata (Apache-2.0), Windows-only; httpx2-jsfetch (BSD-3-Clause), for Pyodide only."
} > "$out"
python3 - "$out" <<'PY'
import sys, re, pathlib
gen = pathlib.Path(sys.argv[1]).read_text()
p = pathlib.Path("LICENSES.md"); t = p.read_text()
start, end = "<!-- deps:start -->", "<!-- deps:end -->"
t = re.sub(re.escape(start) + r".*?" + re.escape(end), f"{start}\n{gen}\n{end}", t, flags=re.S)
p.write_text(t)
PY
echo "LICENSES.md updated"
